#!/usr/bin/env python3
"""Convert a trained DM64 checkpoint into a validated .d64ai package.

    python python/convert.py models/checkpoints/baseline/best.pt \
        --out models/exported/baseline.d64ai --version dm64-base-0001

Writes <out>.d64ai, <out>.manifest.json and <out>.tokens.inc (ACME include for
the game: token ids plus DM64_VOCAB_HASH). The package is re-read and fully
validated before the command succeeds.
"""
import argparse
import datetime
import hashlib
import json
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
import d64ai  # noqa: E402
import quantize  # noqa: E402
import lexicon  # noqa: E402
import tokenizer  # noqa: E402
import vocab  # noqa: E402
from model import ARCH_ID, ModelConfig  # noqa: E402


def build_tokenizer_section(lex=None):
    """kind 1 = text (one character or a merged letter group, PETSCII), 2 = control, 0 = special."""
    lex = lex or lexicon.load("char")
    kinds, display = [], []
    text = set(lex.text_ids)
    for i, name in enumerate(lex.TOKENS):
        if i >= lex.FIRST_CONTROL_ID:
            kinds.append(2)
            display.append(name.encode("ascii"))
        elif i in text:
            kinds.append(1)
            display.append(bytes(tokenizer.ascii_to_petscii(c) for c in name))
        else:
            kinds.append(0)
            display.append(name.encode("ascii"))
    return d64ai.tokenizer_section(lex.TOKENS, kinds, display, tokenizer.petscii_input_table())


def tokens_inc(vocab_hash, version, lex):
    lines = [f"; DM64 token ids - generated by python/convert.py for {version}. Do not edit.",
             f"DM64_VOCAB_HASH = ${vocab_hash:08x}",
             f"DM64_VOCAB_SIZE = {lex.VOCAB_SIZE}",
             f"DM64_FIRST_CONTROL_ID = ${lex.FIRST_CONTROL_ID:02x}"]
    for name in lex.SPECIALS:
        lines.append(f"TOK_{name} = ${lex.ID[name]:02x}")
    for i in range(lex.FIRST_CONTROL_ID, lex.VOCAB_SIZE):
        lines.append(f"TOK_{lex.TOKENS[i].replace(':', '_')} = ${i:02x}")
    return "\n".join(lines) + "\n"


def convert(checkpoint_path, out, version):
    ck_bytes = Path(checkpoint_path).read_bytes()
    ck = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    lex = lexicon.load(ck.get("tokenizer", "char"))
    if ck.get("vocab") != lex.TOKENS:
        raise SystemExit(f"checkpoint vocabulary differs from lexicon {lex.name!r}; refusing to convert")
    mcfg = ModelConfig(**ck["model_config"]).validate()
    cfg = mcfg.to_dict()
    tensors = quantize.quantize_state(ck["model"], cfg)
    qerr = quantize.quantization_error(ck["model"], tensors, cfg)
    tok_section = build_tokenizer_section(lex)
    source_sha = hashlib.sha256(ck_bytes).digest()
    metadata = "\n".join([
        f"created={datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds')}",
        f"model_version={version}", f"arch_id={ARCH_ID}", f"tokenizer={lex.name}",
        f"train_config={json.dumps(ck['config'], sort_keys=True)}",
        f"train_step={ck['step']}", f"val_loss_float={ck.get('val_loss')}",
        f"checkpoint_sha256={source_sha.hex()}",
    ]) + "\n"
    image = d64ai.write(
        cfg, tensors, tok_section, metadata,
        rms_eps_q32=round(mcfg.rms_eps * 2 ** 32),
        inv_sqrt_head_q24=round(2 ** 24 / mcfg.head_dim ** 0.5),
        special={n: lex.ID[n] for n in lex.SPECIALS},
        first_control_id=lex.FIRST_CONTROL_ID, model_version=version,
        model_name=version.upper().encode("ascii"), source_sha256=source_sha)
    pkg = d64ai.read(image)                      # full validation round trip
    for key, t in tensors.items():
        got = pkg.tensors[key]
        same = (got.w == t.w).all() and (got.s == t.s).all() if isinstance(t, d64ai.Matrix) \
            else (got == t).all()
        if not same:
            raise SystemExit(f"round-trip mismatch in {key}")

    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(image)
    h = pkg.header
    manifest = {
        "file": out.name, "bytes": len(image), "sha256": hashlib.sha256(image).hexdigest(),
        "header": {k: (v.hex() if isinstance(v, bytes) else v) for k, v in h.items()},
        "tensors": pkg.directory, "parameters": int(sum(
            (t.w.size if isinstance(t, d64ai.Matrix) else len(t)) for t in tensors.values())),
        "quantization_rel_rms_error_max": qerr, "metadata": metadata.splitlines(),
    }
    out.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    out.with_suffix(".tokens.inc").write_text(tokens_inc(h["vocab_hash"], version, lex))
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint")
    parser.add_argument("--out", required=True)
    parser.add_argument("--version", required=True, help="ASCII, at most 16 characters")
    args = parser.parse_args()
    if len(args.version) > 16:
        raise SystemExit("--version must be at most 16 characters")
    m = convert(args.checkpoint, args.out, args.version)
    print(f"wrote {args.out}: {m['bytes']:,} bytes, {m['parameters']:,} parameters, "
          f"sha256 {m['sha256'][:16]}...")
    print("max relative quantization error per kind:",
          {k: round(v, 4) for k, v in m["quantization_rel_rms_error_max"].items()})


if __name__ == "__main__":
    main()
