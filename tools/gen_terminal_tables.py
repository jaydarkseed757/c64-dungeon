#!/usr/bin/env python3
"""Generate terminal/source/generated/scene_tables.asm from python/vocab.py.

Token ids, display names (ACME !scr strings) for the scene picker, and the
vocabulary hash the terminal requires from the model (AI_PB_EXPECT_HASH).
"""
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
import convert  # noqa: E402
import lexicon  # noqa: E402
import vocab  # noqa: E402

GROUPS = {
    "loc": ("LOC", vocab.CONTROL_GROUPS["LOC"]),
    "room": ("ROOM", vocab.CONTROL_GROUPS["ROOM"]),
    "mon": ("MON", vocab.CONTROL_GROUPS["MON"]),
    "mst": ("MST", ["HEALTHY", "WOUNDED", "DYING"]),
    "cont": ("OBJ", ["CHEST", "SARCOPHAGUS", "ALTAR", "BOOKSHELF", "BONES", "FOUNTAIN", "STATUE"]),
    "obj": ("OBJ", vocab.CONTROL_GROUPS["OBJ"]),
    "item": ("ITEM", vocab.CONTROL_GROUPS["ITEM"]),
    "env": ("ENV", vocab.CONTROL_GROUPS["ENV"]),
    "hp": ("HP", vocab.CONTROL_GROUPS["HP"]),
    "cout": ("OUT", ["HIT", "MISS", "CRIT", "KILLED"]),
}


def main():
    lex = lexicon.load(lexicon.DEFAULT)
    vhash = zlib.crc32(convert.build_tokenizer_section(lex)) & 0xFFFFFFFF
    lines = ["; Generated by tools/gen_terminal_tables.py from python/vocab.py. Do not edit.",
             f"VOCAB_HASH = ${vhash:08x}",
             f"; lexicon: {lex.name}",
             f"TOK_BOS = ${lex.BOS:02x}", f"TOK_SEP = ${lex.SEP:02x}"]
    for name in lex.TOKENS[lex.FIRST_CONTROL_ID:]:
        lines.append(f"TOK_{name.replace(':', '_')} = ${lex.ID[name]:02x}")
    lines.append("vocab_hash_bytes: !byte " + ",".join(f"${(vhash >> (8 * i)) & 0xff:02x}" for i in range(4)))
    for key, (group, values) in GROUPS.items():
        lines.append(f"grp_{key}_n = {len(values)}")
        lines.append(f"grp_{key}_id: !byte " + ",".join(f"${lex.ID[f'{group}:{v}']:02x}" for v in values))
        lines.append(f"grp_{key}_lo: !byte " + ",".join(f"<grp_{key}_s{i}" for i in range(len(values))))
        lines.append(f"grp_{key}_hi: !byte " + ",".join(f">grp_{key}_s{i}" for i in range(len(values))))
        for i, v in enumerate(values):
            lines.append(f'grp_{key}_s{i}: !scr "{v.lower().replace("_", " ")}", 0')
    out = ROOT / "terminal/source/generated/scene_tables.asm"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} (vocab hash ${vhash:08x})")


if __name__ == "__main__":
    main()
