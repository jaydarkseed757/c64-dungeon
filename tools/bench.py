#!/usr/bin/env python3
"""BENCH.PRG support: request list, table generator, reference check, runners.

    python tools/bench.py tables                    write bench/source/generated/bench_tables.asm
    python tools/bench.py expect -n 20              reference tokens and CRC for 20 requests
    python tools/bench.py vice --requests 2         run BENCH.PRG in VICE and check it
    python tools/bench.py ultimate [--turbo]        run BENCH.PRG on the C64 Ultimate (REST; resets
                                                    the C64, the REU keeps the model)

BENCH.PRG (bench/source/bench.asm) cycles through REQUESTS with the game's
settings (temperature 0.8, top-8, at most 48 tokens). Request k (0-based) uses
REQUESTS[k % len] and the xorshift32 seed seed(k), so python/reference_int.py
reproduces every token. The C64 keeps a CRC32 (zlib) over the generated token
ids of all completed requests; this tool compares it with the reference.

Results block in C64 RAM ($C800, little-endian), read by this tool:
    +0  "DMB1"            +4  phase: 0 boot, 1 running, 2 done, 3 error
    +5  status (AI_*)     +6  requests completed (16)
    +8  prompt tokens     +12 prompt cycles      (CIA2 1 MHz-domain cycles, 32-bit)
    +16 generated tokens  +20 generation cycles
    +24 min step cycles   +28 max step cycles    +32 last step cycles
    +36 output characters +40 CRC32 (final)      +44 elapsed tenths (wall clock, 16)
    +46 clock: 1 TOD, 2 CIA (TOD did not run)    +47 turbo (1 = 64 MHz)
    +48 total CIA cycles since start (32)        +52 kHz of the CIA clock (16, measured)
Configuration in the PRG (patched by tests): cfg_secs (16, default 300),
cfg_max_req (16, 0 = no limit), cfg_max_tok (8, default 48).
"""
import argparse
import struct
import sys
import time
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "python"), str(ROOT / "tools"), str(ROOT / "tests")]
import convert  # noqa: E402
import lexicon  # noqa: E402

MAX_TOKENS, TOP_K, INV_TEMP_Q8 = 48, 8, 320
RESULTS = 0xC800
TABLES = ROOT / "bench/source/generated/bench_tables.asm"
PRG = ROOT / "bench/build/bench.prg"

# (label shown on the C64, context tokens, typed prompt)
REQUESTS = [
    ("room: crypt, burial chamber", ["TASK:ROOM", "LOC:CRYPT", "ROOM:BURIAL_CHAMBER"], None),
    ("monster: keep, orc", ["TASK:MONSTER", "LOC:KEEP", "MON:ORC", "MST:HEALTHY"], None),
    ("room: cavern, lair, goblin", ["TASK:ROOM", "LOC:CAVERN", "ROOM:LAIR", "MON:GOBLIN"], None),
    ("kill: spider", ["TASK:COMBAT", "MON:SPIDER", "MST:DEAD", "ACT:ATTACK", "OUT:KILLED", "HP:MID"], None),
    ("treasure: sword", ["TASK:TREASURE", "ITEM:SWORD", "OUT:FOUND"], None),
    ("door: locked", ["TASK:ACTION", "OBJ:DOOR", "ACT:OPEN", "OUT:LOCKED"], None),
    ("typed: describe an ancient dungeon", ["TASK:FREE"], "describe an ancient dungeon"),
    ("room: mine, library", ["TASK:ROOM", "LOC:MINE", "ROOM:LIBRARY"], None),
    ("monster: sewer, rat", ["TASK:MONSTER", "LOC:SEWER", "MON:RAT", "MST:HEALTHY"], None),
    ("search: trap", ["TASK:ACTION", "ACT:SEARCH", "OUT:TRAP"], None),
    ("door: unlocked with key", ["TASK:ACTION", "OBJ:DOOR", "ITEM:KEY", "ACT:USE", "OUT:SUCCESS"], None),
    ("typed: what is that", ["TASK:FREE"], "what is that"),
]


def seed(k):
    """xorshift32 seed of request k (bytes k lo, k hi, $5a, $a5; never zero)."""
    return (k & 0xFF) | ((k >> 8) & 0xFF) << 8 | 0x5A << 16 | 0xA5 << 24


def prompt_ids(lex, i):
    _, ctx, typed = REQUESTS[i % len(REQUESTS)]
    return lex.encode_prompt(ctx, typed)


def write_tables():
    lex = lexicon.load(lexicon.DEFAULT)
    vhash = zlib.crc32(convert.build_tokenizer_section(lex)) & 0xFFFFFFFF
    lines = ["; Generated by tools/bench.py tables. Do not edit.", f"; lexicon: {lex.name}",
             f"N_REQ = {len(REQUESTS)}",
             "vocab_hash_bytes: !byte " + ",".join(f"${(vhash >> (8 * i)) & 0xff:02x}" for i in range(4)),
             "req_lo: !byte " + ",".join(f"<req{i}" for i in range(len(REQUESTS))),
             "req_hi: !byte " + ",".join(f">req{i}" for i in range(len(REQUESTS))),
             "lab_lo: !byte " + ",".join(f"<lab{i}" for i in range(len(REQUESTS))),
             "lab_hi: !byte " + ",".join(f">lab{i}" for i in range(len(REQUESTS)))]
    for i, (label, _, _) in enumerate(REQUESTS):
        ids = prompt_ids(lex, i)
        lines.append(f"req{i}: !byte {len(ids)}," + ",".join(f"${t:02x}" for t in ids))
        lines.append(f'lab{i}: !scr "[{label}]", 0')
    TABLES.parent.mkdir(parents=True, exist_ok=True)
    TABLES.write_text("\n".join(lines) + "\n")
    print(f"wrote {TABLES}")


def expected(package, n, max_tokens=MAX_TOKENS, verbose=False):
    """Reference run of the first n requests -> (crc, gen_tokens, prompt_tokens, texts)."""
    from reference_int import load
    engine = load(package)
    lex = lexicon.load(lexicon.DEFAULT)
    crc, gen, pre, texts = 0, 0, 0, []
    for k in range(n):
        ids = prompt_ids(lex, k)
        out = engine.generate(ids, max_chars=max_tokens, inv_temp_q8=INV_TEMP_Q8, top_k=TOP_K, seed=seed(k))
        crc = zlib.crc32(bytes(out), crc)
        pre += len(ids)
        # forward passes during generation: every sampled token except the last one
        gen += len(out) - 1
        texts.append(engine.decode(out))
        if verbose:
            print(f"{k:3d} {REQUESTS[k % len(REQUESTS)][0]:36} {texts[-1]}")
    return crc, gen, pre, texts


def parse(block):
    f = {"sig": bytes(block[0:4]), "phase": block[4], "status": block[5]}
    f["requests"], = struct.unpack_from("<H", block, 6)
    names = ["prompt_tokens", "prompt_cycles", "gen_tokens", "gen_cycles", "min_step", "max_step",
             "last_step", "chars", "crc"]
    for i, name in enumerate(names):
        f[name], = struct.unpack_from("<I", block, 8 + 4 * i)
    f["tenths"], = struct.unpack_from("<H", block, 44)
    f["clock"] = {1: "TOD", 2: "CIA"}.get(block[46], "?")
    f["turbo"] = block[47]
    f["cia_total"], = struct.unpack_from("<I", block, 48)
    f["khz"], = struct.unpack_from("<H", block, 52)
    return f


def report(f, ref=None, wall=None):
    khz = f["khz"] or 1000
    ms = lambda cyc: cyc / khz  # noqa: E731
    secs = f["tenths"] / 10
    print(f"clock {f['clock']}, CIA {khz} kHz, turbo {'64 MHz' if f['turbo'] else 'off'}")
    print(f"time {secs:.1f} s" + (f"   (Mac wall clock {wall:.1f} s)" if wall else ""))
    print(f"requests {f['requests']}, characters {f['chars']}")
    if f["prompt_tokens"]:
        print(f"prompt tokens {f['prompt_tokens']}, {ms(f['prompt_cycles'] / f['prompt_tokens']):.0f} ms/token")
    if f["gen_tokens"]:
        print(f"generated tokens {f['gen_tokens']}, {ms(f['gen_cycles'] / f['gen_tokens']):.0f} ms/token "
              f"(min {ms(f['min_step']):.0f}, max {ms(f['max_step']):.0f})")
    if secs:
        print(f"speed {f['gen_tokens'] / secs:.2f} tokens/s, {f['chars'] / secs:.2f} characters/s")
    print(f"CRC {f['crc']:08x}" + ("" if ref is None else
                                   ("  matches the reference" if ref[0] == f["crc"] else f"  REFERENCE {ref[0]:08x}")))


def run_vice(args):
    from vice_harness import Vice
    import subprocess
    subprocess.run(["make", "bench"], cwd=ROOT, check=True, capture_output=True)
    labels = labels_of(ROOT / "bench/build/bench.lbl")
    with Vice(reu_image=args.model) as vm:
        vm.load_prg(PRG)
        vm.write(labels["cfg_max_req"], struct.pack("<H", args.requests))
        vm.write(labels["cfg_max_tok"], bytes([args.max_tokens]))
        if args.secs:
            vm.write(labels["cfg_secs"], struct.pack("<H", args.secs))
        vm.run_until(labels["bench_done"], timeout=args.timeout)
        f = parse(vm.read(RESULTS, RESULTS + 63))
        if args.png:
            from ult_screenshot import capture_memory, write_png
            width, lines = capture_memory(None, read=lambda a, n: bytes(vm.read(a, a + n - 1)))
            write_png(args.png, width, lines, scale=2)
            print(f"screen saved to {args.png}")
    ref = expected(args.model, f["requests"], args.max_tokens, verbose=True)
    report(f, ref)
    return 0 if ref[0] == f["crc"] and f["phase"] == 2 else 1


def labels_of(path):
    out = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[1] == "=":
            out[parts[0]] = int(parts[2].lstrip("$"), 16)
    return out


TURBO = "/configs/U64%20Specific%20Settings/Turbo%20Control"


def turbo_get(u):
    import json
    return json.loads(u.call("GET", TURBO))["U64 Specific Settings"]["Turbo Control"]["current"]


def turbo_set(u, value):
    """Change Turbo Control for this run only (not saved to flash), then read it back."""
    import urllib.parse
    u.call("PUT", TURBO + "?value=" + urllib.parse.quote(value))
    got = turbo_get(u)
    if got != value:
        raise SystemExit(f"Turbo Control reads {got!r} after setting {value!r}")


def run_ultimate(args):
    import subprocess
    from terminal_hw import Ult
    subprocess.run(["make", "bench"], cwd=ROOT, check=True, capture_output=True)
    u = Ult(args.host)
    before = turbo_get(u)
    print(f"Turbo Control: {before}")
    changed = args.turbo and before != "C64U Turbo Registers"
    if changed:
        turbo_set(u, "C64U Turbo Registers")
        print("Turbo Control set to C64U Turbo Registers for this run (not saved)")
    try:
        return _run_ultimate(u, args)
    finally:
        if changed:
            turbo_set(u, before)
            print(f"Turbo Control restored to {before} (verified)")


def _run_ultimate(u, args):
    u.run_prg(PRG)
    t0 = time.time()
    last = None
    while True:
        time.sleep(5)
        f = parse(u.read(RESULTS, 64))
        if f["sig"] == b"DMB1" and f["phase"] in (2, 3):
            break
        if f["sig"] == b"DMB1" and (f["requests"], f["gen_tokens"]) != last:
            last = (f["requests"], f["gen_tokens"])
            print(f"  {f['tenths'] / 10:6.1f} s  requests {f['requests']}  tokens {f['gen_tokens']}", flush=True)
        if time.time() - t0 > args.timeout:
            raise SystemExit("timeout waiting for BENCH.PRG to finish")
    wall = time.time() - t0
    ref = expected(args.model, f["requests"])
    report(f, ref, wall)
    return 0 if ref[0] == f["crc"] else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("tables")
    e = sub.add_parser("expect")
    e.add_argument("-n", type=int, default=12)
    e.add_argument("--model", default=str(ROOT / "models/exported/baseline_bpe72_v3q.d64ai"))
    v = sub.add_parser("vice")
    v.add_argument("--requests", type=int, default=1, help="stop after N requests (0 = time only)")
    v.add_argument("--max-tokens", type=int, default=6)
    v.add_argument("--model", default=str(ROOT / "models/exported/bringup_bpe72.d64ai"))
    v.add_argument("--secs", type=int, default=0, help="run length (default: the PRG's 300 s)")
    v.add_argument("--png", help="save the final screen as a PNG")
    v.add_argument("--timeout", type=int, default=1800)
    u = sub.add_parser("ultimate")
    u.add_argument("--host", default=__import__("os").environ.get("ULT_HOST", "192.168.10.148"))
    u.add_argument("--model", default=str(ROOT / "models/exported/baseline_bpe72_v3q.d64ai"))
    u.add_argument("--timeout", type=int, default=420)
    u.add_argument("--turbo", action="store_true",
                   help="switch Turbo Control on for the run if it is off, then restore it")
    args = ap.parse_args()
    if args.cmd == "tables":
        write_tables()
    elif args.cmd == "expect":
        crc, gen, pre, _ = expected(args.model, args.n, verbose=True)
        print(f"CRC {crc:08x}, generated {gen}, prompt {pre}")
    elif args.cmd == "vice":
        sys.exit(run_vice(args))
    else:
        sys.exit(run_ultimate(args))


if __name__ == "__main__":
    main()
