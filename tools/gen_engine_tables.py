#!/usr/bin/env python3
"""Generate constant tables for the ACME engine from python/fixedpoint.py.

Writes engine/source/generated/exp_table.asm: exp(-i/64) in Q0.24 for
i = 0..1024, 3 bytes per entry. Run by `make engine`.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
from fixedpoint import EXP_TABLE  # noqa: E402


def planes(name, values):
    lines = []
    for b in range(3):
        lines.append(f"{name}{b}:")
        row = [(v >> (8 * b)) & 0xFF for v in values]
        for i in range(0, len(row), 16):
            lines.append("    !byte " + ",".join(f"${x:02x}" for x in row[i:i + 16]))
    return lines


def interleaved(name, values):
    """3 bytes per entry, little-endian: one 6-byte REU fetch gets E[i] and E[i+1]."""
    data = b"".join(v.to_bytes(3, "little") for v in values)
    lines = [f"{name}:"]
    for i in range(0, len(data), 16):
        lines.append("    !byte " + ",".join(f"${x:02x}" for x in data[i:i + 16]))
    return lines


out = ROOT / "engine/source/generated/exp_table.asm"
out.write_text("\n".join(["; exp(-i/64) * 2^24, i = 0..1024, 3 bytes per entry. Generated by",
                          "; tools/gen_engine_tables.py. engine_init copies it to the REU (REU_EXP).",
                          f"EXP_ENTRIES = {len(EXP_TABLE)}"] + interleaved("exp_tab", EXP_TABLE)) + "\n")
print(f"wrote {out}")
