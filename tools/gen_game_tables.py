#!/usr/bin/env python3
"""Generate game/source/generated/game_tables.asm from python/vocab.py.

Maps the game's own ids (monsters, items, room types, floors) to the model's
control tokens, and provides display names (ACME !scr, lowercase) used by the
fallback text. One source of truth: if vocab.py changes, regenerate.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
import zlib  # noqa: E402

import convert  # noqa: E402
import lexicon  # noqa: E402

MONSTERS = [("RAT", "rat"), ("BAT", "bat"), ("SKELETON", "skeleton"), ("GOBLIN", "goblin"),
            ("ZOMBIE", "zombie"), ("SPIDER", "giant spider"), ("ORC", "orc"), ("TROLL", "cave troll"),
            ("DARK_MAGE", "dark mage"), ("DRAGON", "dragon")]
# item id 0 = none; ids 1..15
ITEMS = [None, ("GOLD", "gold"), ("POTION", "potion"), ("DAGGER", "dagger"), ("SWORD", "sword"),
         ("AXE", "axe"), ("MACE", "mace"), ("ARMOR", "leather armor"), ("ARMOR", "chain mail"),
         ("SHIELD", "shield"), ("HELM", "helm"), ("KEY", "key"), ("SCROLL", "scroll"),
         ("RING", "ring"), ("GEM", "gem"), ("AMULET", "amulet of dawn")]
ROOMS = [("HALL", "hall"), ("BURIAL_CHAMBER", "burial chamber"), ("TREASURE_ROOM", "treasure room"),
         ("LAIR", "lair"), ("LIBRARY", "library"), ("ARMORY", "armory"),
         ("SECRET_CHAMBER", "secret chamber"), ("TRAP_ROOM", "strange room"),
         ("MAGIC_CHAMBER", "magic chamber"), ("SHRINE", "shrine"), ("PRISON", "prison"),
         ("STAIRS", "stairwell"), ("BOSS_ROOM", "great hall")]
FLOORS = [("CRYPT", "crypt"), ("SEWER", "sewer"), ("MINE", "mine"), ("CAVERN", "cavern"), ("KEEP", "keep")]


LEX = lexicon.load(lexicon.DEFAULT)


def table(lines, name, group, entries):
    ids, names = [], []
    for e in entries:
        if e is None:
            ids.append("$00")
            names.append("")
        else:
            ids.append(f"${LEX.ID[f'{group}:{e[0]}']:02x}")
            names.append(e[1])
    lines.append(f"{name}_tok: !byte " + ",".join(ids))
    lines.append(f"{name}_lo: !byte " + ",".join(f"<{name}_s{i}" for i in range(len(entries))))
    lines.append(f"{name}_hi: !byte " + ",".join(f">{name}_s{i}" for i in range(len(entries))))
    for i, n in enumerate(names):
        lines.append(f'{name}_s{i}: !scr "{n}", 0')


def main():
    lines = ["; Generated by tools/gen_game_tables.py from python/lexicon.py. Do not edit.",
             f"; lexicon: {LEX.name}",
             f"TOK_BOS = ${LEX.BOS:02x}", f"TOK_SEP = ${LEX.SEP:02x}"]
    vhash = zlib.crc32(convert.build_tokenizer_section(LEX)) & 0xFFFFFFFF
    lines.append(f"VOCAB_HASH = ${vhash:08x}")
    lines.append("vocab_hash_bytes: !byte " + ",".join(f"${(vhash >> (8 * i)) & 0xff:02x}" for i in range(4)))
    for name in LEX.TOKENS[LEX.FIRST_CONTROL_ID:]:
        lines.append(f"TOK_{name.replace(':', '_')} = ${LEX.ID[name]:02x}")
    lines.append(f"N_MON = {len(MONSTERS)}")
    lines.append(f"N_ITEM = {len(ITEMS)}")
    lines.append(f"N_ROOMT = {len(ROOMS)}")
    table(lines, "mon", "MON", MONSTERS)
    table(lines, "item", "ITEM", ITEMS)
    table(lines, "roomt", "ROOM", ROOMS)
    table(lines, "floor", "LOC", FLOORS)
    out = ROOT / "game/source/generated/game_tables.asm"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
